using System.Globalization;
using System.Security;
using System.Text;
using ErpPrinter.Settings;

namespace ErpPrinter.Policy;

/// <summary>
/// Generates the Group Policy templates (ADMX and the en-US ADML) from the global settings schema, so policy always matches
/// what the code understands. Output uses CRLF line endings and UTF-8 without BOM, as Group Policy tooling expects.
/// Policies write to HKLM\SOFTWARE\Policies\ErpPrinter, which overrides the machine configuration. Printer profiles are dynamic
/// registry keys that ADMX cannot model; push those with Group Policy Preferences or Intune instead.
/// </summary>
public static class PolicyTemplateGenerator
{
    private const string PolicyKey = @"Software\Policies\ErpPrinter";

    public sealed record PolicyTemplates(string Admx, string Adml);

    /// <param name="generatedBy">Name of the generator quoted in the header comment of both files.</param>
    public static PolicyTemplates Generate(string revision = "1.0", string generatedBy = "erpprinter schema")
    {
        var schema = Schema.Global;
        var defaults = GlobalSettings.Defaults().Values;
        var groups = schema.Select(s => s.Group).Distinct().ToList();

        var strings = new OrderedStrings();
        strings.Set("ErpPrinter", "ERP Printer");
        strings.Set("SUPPORTED_ErpPrinter", "ERP Printer 1.0 and later");
        var presentations = new StringBuilder();
        var admx = new StringBuilder();

        admx.AppendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
        admx.AppendLine($"<!-- Generated by {generatedBy} from the ErpPrinter settings schema. Do not edit by hand. -->");
        admx.AppendLine($"<policyDefinitions xmlns:xsd=\"http://www.w3.org/2001/XMLSchema\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" revision=\"{revision}\" schemaVersion=\"1.0\" xmlns=\"http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions\">");
        admx.AppendLine("  <policyNamespaces>");
        admx.AppendLine("    <target prefix=\"erpprinter\" namespace=\"ErpPrinter.Policies.ErpPrinter\" />");
        admx.AppendLine("    <using prefix=\"windows\" namespace=\"Microsoft.Policies.Windows\" />");
        admx.AppendLine("  </policyNamespaces>");
        admx.AppendLine($"  <resources minRequiredRevision=\"{revision}\" />");
        admx.AppendLine("  <supportedOn>");
        admx.AppendLine("    <definitions>");
        admx.AppendLine("      <definition name=\"SUPPORTED_ErpPrinter\" displayName=\"$(string.SUPPORTED_ErpPrinter)\" />");
        admx.AppendLine("    </definitions>");
        admx.AppendLine("  </supportedOn>");
        admx.AppendLine("  <categories>");
        admx.AppendLine("    <category name=\"ErpPrinter\" displayName=\"$(string.ErpPrinter)\" />");
        foreach (var group in groups)
        {
            var id = $"Cat_{group}";
            strings.Set(id, group);
            admx.AppendLine($"    <category name=\"{id}\" displayName=\"$(string.{id})\"><parentCategory ref=\"ErpPrinter\" /></category>");
        }
        admx.AppendLine("  </categories>");
        admx.AppendLine("  <policies>");

        foreach (var s in schema)
        {
            var name = s.Name;
            var def = defaults[name];
            strings.Set(name, s.Label);
            var help = s.Help.Length > 0 ? s.Help : s.Label + ".";
            var defaultText = s.DefaultText
                ?? (s.Type == SettingType.Bool ? ((bool)def ? "enabled" : "disabled")
                    : Text(def) is { Length: > 0 } t ? t : "(empty)");
            strings.Set($"{name}_Help",
                $"{help}\n\nIf you do not configure this policy, the value set on the device (ERP Printer configuration window, installer or registry) is used. Built-in default: {defaultText}.");

            var head = $"    <policy name=\"{name}\" class=\"Machine\" displayName=\"$(string.{name})\" explainText=\"$(string.{name}_Help)\" key=\"{PolicyKey}\"";
            if (s.Type == SettingType.Bool)
            {
                admx.AppendLine($"{head} valueName=\"{name}\">");
                admx.AppendLine($"      <parentCategory ref=\"Cat_{s.Group}\" />");
                admx.AppendLine("      <supportedOn ref=\"SUPPORTED_ErpPrinter\" />");
                admx.AppendLine("      <enabledValue><decimal value=\"1\" /></enabledValue>");
                admx.AppendLine("      <disabledValue><decimal value=\"0\" /></disabledValue>");
            }
            else
            {
                admx.AppendLine($"{head} presentation=\"$(presentation.{name})\">");
                admx.AppendLine($"      <parentCategory ref=\"Cat_{s.Group}\" />");
                admx.AppendLine("      <supportedOn ref=\"SUPPORTED_ErpPrinter\" />");
                admx.AppendLine("      <elements>");
                switch (s.Type)
                {
                    case SettingType.Int:
                        admx.AppendLine($"        <decimal id=\"{name}\" valueName=\"{name}\" minValue=\"{s.Min}\" maxValue=\"{Math.Min((long)s.Max, int.MaxValue)}\" required=\"true\" />");
                        presentations.AppendLine($"      <presentation id=\"{name}\"><decimalTextBox refId=\"{name}\" defaultValue=\"{Text(def)}\">{Escape(s.Label)}:</decimalTextBox></presentation>");
                        break;
                    case SettingType.Choice:
                        admx.AppendLine($"        <enum id=\"{name}\" valueName=\"{name}\" required=\"true\">");
                        foreach (var choice in s.Choices)
                        {
                            var choiceId = $"{name}_{choice}";
                            strings.Set(choiceId, choice);
                            admx.AppendLine($"          <item displayName=\"$(string.{choiceId})\"><value><string>{Escape(choice)}</string></value></item>");
                        }
                        admx.AppendLine("        </enum>");
                        var index = Math.Max(s.Choices.ToList().IndexOf(Text(def)), 0);
                        presentations.AppendLine($"      <presentation id=\"{name}\"><dropdownList refId=\"{name}\" noSort=\"true\" defaultItem=\"{index}\">{Escape(s.Label)}:</dropdownList></presentation>");
                        break;
                    default:
                        admx.AppendLine($"        <text id=\"{name}\" valueName=\"{name}\" maxLength=\"2048\" />");
                        presentations.AppendLine($"      <presentation id=\"{name}\"><textBox refId=\"{name}\"><label>{Escape(s.Label)}:</label></textBox></presentation>");
                        break;
                }
                admx.AppendLine("      </elements>");
            }
            admx.AppendLine("    </policy>");
        }
        admx.AppendLine("  </policies>");
        admx.AppendLine("</policyDefinitions>");

        var adml = new StringBuilder();
        adml.AppendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
        adml.AppendLine($"<!-- Generated by {generatedBy} from the ErpPrinter settings schema. Do not edit by hand. -->");
        adml.AppendLine($"<policyDefinitionResources xmlns:xsd=\"http://www.w3.org/2001/XMLSchema\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" revision=\"{revision}\" schemaVersion=\"1.0\" xmlns=\"http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions\">");
        adml.AppendLine("  <displayName>ERP Printer</displayName>");
        adml.AppendLine("  <description>Machine-wide settings for ERP Printer. Printer profiles are configured with Group Policy Preferences or Intune.</description>");
        adml.AppendLine("  <resources>");
        adml.AppendLine("    <stringTable>");
        foreach (var (id, value) in strings.Entries)
            adml.AppendLine($"      <string id=\"{id}\">{Escape(value)}</string>");
        adml.AppendLine("    </stringTable>");
        adml.AppendLine("    <presentationTable>");
        adml.Append(presentations);
        adml.AppendLine("    </presentationTable>");
        adml.AppendLine("  </resources>");
        adml.AppendLine("</policyDefinitionResources>");

        return new PolicyTemplates(Crlf(admx.ToString()), Crlf(adml.ToString()));
    }

    /// <summary>Writes <c>ErpPrinter.admx</c> and <c>en-US/ErpPrinter.adml</c> under <paramref name="outputDir"/> (UTF-8 without BOM).</summary>
    public static void WriteTo(string outputDir, string revision = "1.0", string generatedBy = "erpprinter schema")
    {
        var templates = Generate(revision, generatedBy);
        var language = Path.Combine(outputDir, "en-US");
        Directory.CreateDirectory(language);
        var utf8 = new UTF8Encoding(false);
        File.WriteAllText(Path.Combine(outputDir, "ErpPrinter.admx"), templates.Admx, utf8);
        File.WriteAllText(Path.Combine(language, "ErpPrinter.adml"), templates.Adml, utf8);
    }

    private static string Text(object value) => value switch
    {
        bool b => b ? "True" : "False",
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => value.ToString() ?? "",
    };

    private static string Escape(string text) => SecurityElement.Escape(text) ?? "";

    private static string Crlf(string text) => text.Replace("\r\n", "\n").Replace("\n", "\r\n");

    /// <summary>String table that keeps insertion order and lets a later Set of the same id replace the value in place.</summary>
    private sealed class OrderedStrings
    {
        private readonly List<(string Id, string Value)> _entries = [];

        public IReadOnlyList<(string Id, string Value)> Entries => _entries;

        public void Set(string id, string value)
        {
            var i = _entries.FindIndex(e => e.Id == id);
            if (i >= 0) _entries[i] = (id, value);
            else _entries.Add((id, value));
        }
    }
}
