using System.Globalization;
using System.Text;
using ErpPrinter.Settings;

namespace ErpPrinter.Policy;

/// <summary>Generates docs/settings.md from the settings schema. Port of build/New-SettingsReference.ps1 (output is byte-identical, LF line endings).</summary>
public static class SettingsReferenceGenerator
{
    public static string Generate(string generatedBy = "build/New-SettingsReference.ps1")
    {
        var lines = new List<string>
        {
            $"<!-- Generated by {generatedBy} from the settings schema. Do not edit by hand. -->",
            "# Settings reference",
            "",
            "Every setting lives in the registry. The configuration window, the MSI properties and the `Set-ErpPrinterSetting` cmdlet all write the same values.",
            "",
            "| Scope | Machine value (GUI, MSI, scripts) | Policy override (GPO, Intune) |",
            "| --- | --- | --- |",
            @"| Global | `HKLM\SOFTWARE\ErpPrinter` | `HKLM\SOFTWARE\Policies\ErpPrinter` |",
            @"| Printer profile | `HKLM\SOFTWARE\ErpPrinter\Printers\<profile>` | `HKLM\SOFTWARE\Policies\ErpPrinter\Printers\<profile>` |",
            "",
            @"A value under `Policies` wins and shows as read-only in the configuration window. A profile that exists only under `Policies` is fully managed by policy. Secrets are never read from `Policies`.",
            "",
        };

        foreach (var scope in new[] { SettingScope.Global, SettingScope.Profile })
        {
            var schema = Schema.For(scope);
            var defaults = scope == SettingScope.Global
                ? GlobalSettings.Defaults().Values
                : PrinterProfile.Create("Example").Values;
            lines.Add(scope == SettingScope.Global ? "## Global settings" : "## Printer profile settings");
            lines.Add("");
            foreach (var group in schema.Select(s => s.Group).Distinct())
            {
                lines.Add($"### {group}");
                lines.Add("");
                if (scope == SettingScope.Global)
                {
                    lines.Add("| Name | Type | Default | Description |");
                    lines.Add("| --- | --- | --- | --- |");
                }
                else
                {
                    lines.Add("| Name | Type | Default | Backends | Description |");
                    lines.Add("| --- | --- | --- | --- | --- |");
                }
                foreach (var s in schema.Where(s => s.Group == group))
                {
                    var description = s.Label + ".";
                    if (s.Help.Length > 0) description += " " + s.Help;
                    var backendCell = scope == SettingScope.Profile
                        ? " " + (s.Backends.Count > 0 ? string.Join(", ", s.Backends) : "all") + " |"
                        : "";
                    lines.Add($"| `{s.Name}` | {FormatType(s)} | {FormatDefault(s, defaults)} |{backendCell} {FormatCell(description)} |");
                }
                lines.Add("");
            }
        }
        return string.Join("\n", lines) + "\n";
    }

    public static void WriteTo(string path, string generatedBy = "build/New-SettingsReference.ps1")
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, Generate(generatedBy), new UTF8Encoding(false));
    }

    private static string FormatDefault(SettingDefinition s, IReadOnlyDictionary<string, object> resolved)
    {
        if (s.DefaultText is not null) return $"`{s.DefaultText}`";
        if (s.DefaultFactory is not null)
        {
            if (s.Name == "PrinterName") return "the profile name";
            if (s.Name == "PipeName") return "`ErpPrinter-<profile name>`";
        }
        if (s.Type == SettingType.Secret) return "";
        var value = resolved.TryGetValue(s.Name, out var v) ? v : "";
        if (s.Type == SettingType.Bool) return value is true ? "1 (on)" : "0 (off)";
        var text = value is IFormattable f ? f.ToString(null, CultureInfo.InvariantCulture) : value.ToString() ?? "";
        return text.Length == 0 ? "(empty)" : $"`{text}`";
    }

    private static string FormatType(SettingDefinition s) => s.Type switch
    {
        SettingType.Bool => "REG_DWORD 0/1",
        SettingType.Int => $"REG_DWORD {s.Min}-{s.Max}",
        SettingType.Choice => "REG_SZ: " + string.Join(", ", s.Choices.Select(c => $"`{c}`")),
        SettingType.Secret => @"REG_BINARY (DPAPI), under `Secrets\<profile>`",
        _ => "REG_SZ",
    };

    private static string FormatCell(string text) => text.Replace("|", "\\|").Replace("\r\n", " ").Replace("\n", " ").Trim();
}
