<#
.SYNOPSIS
    Publishes the three C# executables (Service, Cli, Config) into ONE shared folder, ready for the MSI.
.DESCRIPTION
    Each project is published self-contained for win-x64 (ReadyToRun, no trimming, no single-file; see
    dotnet/Publish.props) into the same folder, so the three executables share one copy of the .NET runtime.
    Afterwards the policy templates, README and LICENSE are copied next to them, giving this payload:

      ErpPrinterService.exe   the "ErpPrinter" Windows service
      erpprinter.exe          command-line tool
      ErpPrinterConfig.exe    configuration GUI (requires administrator)
      *.dll, *.json           runtime, app assemblies, deps/runtimeconfig per executable, appsettings.json
      Policies\               ErpPrinter.admx and en-US\ErpPrinter.adml
      README.md, LICENSE

    build/build.ps1 -Task DotnetPublish calls this script. The version comes from dotnet/Directory.Build.props
    unless -Version is given.
.EXAMPLE
    ./build/Publish-Dotnet.ps1 -OutputDir out/dotnet/payload -UpdateManifestUrl https://github.com/acme/windows-erp-printer/releases/latest/download/latest.json
#>
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingWriteHost', '', Justification = 'Build console output.')]
[CmdletBinding()]
param(
    [string] $OutputDir,
    [ValidatePattern('^\d{1,3}\.\d{1,3}\.\d{1,5}$')]
    [string] $Version,
    [string] $UpdateManifestUrl = '',
    [string] $Commit = '',
    [string] $Configuration = 'Release',
    [string] $RuntimeIdentifier = 'win-x64'
)
$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1 leaves $PSScriptRoot empty in param() defaults under -File, so resolve here.
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$dotnetDir = Join-Path $root 'dotnet'
if (-not $OutputDir) { $OutputDir = Join-Path $root 'out\dotnet\payload' }
if (-not $Version) {
    $props = [xml](Get-Content -LiteralPath (Join-Path $dotnetDir 'Directory.Build.props') -Raw)
    $Version = [string]($props.Project.PropertyGroup | Where-Object { $_.Version } | Select-Object -First 1).Version
}
if ($Version -notmatch '^\d{1,3}\.\d{1,3}\.\d{1,5}$') { throw "Version '$Version' is not major.minor.patch." }
if (-not $Commit) { try { $Commit = (git -C $root rev-parse --short HEAD 2>$null) } catch { $Commit = '' } }
if (-not $Commit) { $Commit = 'local' }
if (-not (Get-Command dotnet -ErrorAction SilentlyContinue)) { throw 'The dotnet SDK is not on PATH.' }

if (Test-Path -LiteralPath $OutputDir) { Remove-Item -LiteralPath $OutputDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$OutputDir = (Resolve-Path -LiteralPath $OutputDir).Path

# The executables, in the order they are published, and the file each one must produce.
$apps = @(
    @{ Project = 'ErpPrinter.Service'; Exe = 'ErpPrinterService.exe' }
    @{ Project = 'ErpPrinter.Cli'; Exe = 'erpprinter.exe' }
    @{ Project = 'ErpPrinter.Config'; Exe = 'ErpPrinterConfig.exe' }
)
foreach ($app in $apps) {
    Write-Host "==> dotnet publish $($app.Project) $Version ($Commit) -> $OutputDir" -ForegroundColor Cyan
    $publishArgs = @(
        'publish', (Join-Path $dotnetDir "src\$($app.Project)\$($app.Project).csproj")
        '-c', $Configuration
        '-r', $RuntimeIdentifier
        '--self-contained'
        '-o', $OutputDir
        "-p:Version=$Version"
        "-p:UpdateManifestUrl=$UpdateManifestUrl"
        "-p:BuildCommit=$Commit"
        '-nologo'
        '-v:minimal'
    )
    & dotnet @publishArgs
    if ($LASTEXITCODE) { throw "dotnet publish $($app.Project) failed with exit code $LASTEXITCODE." }
    if (-not (Test-Path -LiteralPath (Join-Path $OutputDir $app.Exe))) { throw "$($app.Exe) was not produced by $($app.Project)." }
}

# Policy templates: generated by the PowerShell generators today, by "erpprinter schema --admx" once that exists
# (see build.ps1 -Task DotnetGenerate). Either way they are committed under policies/.
Copy-Item -LiteralPath (Join-Path $root 'policies') -Destination (Join-Path $OutputDir 'Policies') -Recurse
Copy-Item -LiteralPath (Join-Path $root 'README.md'), (Join-Path $root 'LICENSE') -Destination $OutputDir
Write-Host ("Published {0} files ({1:N0} MB) to {2}" -f @(Get-ChildItem -LiteralPath $OutputDir -Recurse -File).Count, ((Get-ChildItem -LiteralPath $OutputDir -Recurse -File | Measure-Object Length -Sum).Sum / 1MB), $OutputDir)
