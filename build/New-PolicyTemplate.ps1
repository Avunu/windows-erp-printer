<#
.SYNOPSIS
    Generates policies/ErpPrinter.admx and policies/en-US/ErpPrinter.adml from the module's
    global settings schema, so Group Policy always matches what the code understands.
.DESCRIPTION
    Policies write to HKLM\SOFTWARE\Policies\ErpPrinter, which overrides the machine
    configuration. Printer profiles are dynamic registry keys that ADMX cannot model; push
    those with Group Policy Preferences (Registry) or Intune instead (see docs/deployment.md).
#>
[CmdletBinding()]
param(
    [string] $OutputDir = (Join-Path $PSScriptRoot '..\policies'),
    [string] $Revision = '1.0'
)
$ErrorActionPreference = 'Stop'
$module = Import-Module (Join-Path $PSScriptRoot '..\src\Modules\ErpPrinter\ErpPrinter.psd1') -Force -PassThru
$schema = @(Get-ErpPrinterSettingSchema -Scope Global)
$defaults = & $module { Resolve-ErpSettings -Schema $script:ErpGlobalSchema }

function ConvertTo-XmlText([string] $Text) { [Security.SecurityElement]::Escape($Text) }

$key = 'Software\Policies\ErpPrinter'
$groups = @($schema | ForEach-Object Group | Select-Object -Unique)
$admx = New-Object System.Text.StringBuilder
$adml = New-Object System.Text.StringBuilder
$strings = [ordered]@{
    ErpPrinter           = 'ERP Printer'
    SUPPORTED_ErpPrinter = 'ERP Printer 1.0 and later'
}
$presentations = New-Object System.Text.StringBuilder

[void]$admx.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$admx.AppendLine('<!-- Generated by build/New-PolicyTemplate.ps1 from the ErpPrinter settings schema. Do not edit by hand. -->')
[void]$admx.AppendLine("<policyDefinitions xmlns:xsd=`"http://www.w3.org/2001/XMLSchema`" xmlns:xsi=`"http://www.w3.org/2001/XMLSchema-instance`" revision=`"$Revision`" schemaVersion=`"1.0`" xmlns=`"http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions`">")
[void]$admx.AppendLine('  <policyNamespaces>')
[void]$admx.AppendLine('    <target prefix="erpprinter" namespace="ErpPrinter.Policies.ErpPrinter" />')
[void]$admx.AppendLine('    <using prefix="windows" namespace="Microsoft.Policies.Windows" />')
[void]$admx.AppendLine('  </policyNamespaces>')
[void]$admx.AppendLine("  <resources minRequiredRevision=`"$Revision`" />")
[void]$admx.AppendLine('  <supportedOn>')
[void]$admx.AppendLine('    <definitions>')
[void]$admx.AppendLine('      <definition name="SUPPORTED_ErpPrinter" displayName="$(string.SUPPORTED_ErpPrinter)" />')
[void]$admx.AppendLine('    </definitions>')
[void]$admx.AppendLine('  </supportedOn>')
[void]$admx.AppendLine('  <categories>')
[void]$admx.AppendLine('    <category name="ErpPrinter" displayName="$(string.ErpPrinter)" />')
foreach ($group in $groups) {
    $id = "Cat_$group"
    $strings[$id] = $group
    [void]$admx.AppendLine("    <category name=`"$id`" displayName=`"`$(string.$id)`"><parentCategory ref=`"ErpPrinter`" /></category>")
}
[void]$admx.AppendLine('  </categories>')
[void]$admx.AppendLine('  <policies>')

foreach ($s in $schema) {
    $name = $s.Name
    $default = $defaults[$name]
    $strings[$name] = $s.Label
    $help = $s.Help
    if (-not $help) { $help = $s.Label + '.' }
    $defaultText = if ($s.DefaultText) { $s.DefaultText } elseif ($s.Type -eq 'Bool') { if ($default) { 'enabled' } else { 'disabled' } } elseif ("$default" -ne '') { "$default" } else { '(empty)' }
    $strings["${name}_Help"] = "$help`n`nIf you do not configure this policy, the value set on the device (ERP Printer configuration window, installer or registry) is used. Built-in default: $defaultText."

    $head = "    <policy name=`"$name`" class=`"Machine`" displayName=`"`$(string.$name)`" explainText=`"`$(string.${name}_Help)`" key=`"$key`""
    switch ($s.Type) {
        'Bool' {
            [void]$admx.AppendLine("$head valueName=`"$name`">")
            [void]$admx.AppendLine("      <parentCategory ref=`"Cat_$($s.Group)`" />")
            [void]$admx.AppendLine('      <supportedOn ref="SUPPORTED_ErpPrinter" />')
            [void]$admx.AppendLine('      <enabledValue><decimal value="1" /></enabledValue>')
            [void]$admx.AppendLine('      <disabledValue><decimal value="0" /></disabledValue>')
        }
        default {
            [void]$admx.AppendLine("$head presentation=`"`$(presentation.$name)`">")
            [void]$admx.AppendLine("      <parentCategory ref=`"Cat_$($s.Group)`" />")
            [void]$admx.AppendLine('      <supportedOn ref="SUPPORTED_ErpPrinter" />')
            [void]$admx.AppendLine('      <elements>')
            switch ($s.Type) {
                'Int' {
                    [void]$admx.AppendLine("        <decimal id=`"$name`" valueName=`"$name`" minValue=`"$($s.Min)`" maxValue=`"$([Math]::Min([long]$s.Max, 2147483647))`" required=`"true`" />")
                    [void]$presentations.AppendLine("      <presentation id=`"$name`"><decimalTextBox refId=`"$name`" defaultValue=`"$default`">$(ConvertTo-XmlText $s.Label):</decimalTextBox></presentation>")
                }
                'Choice' {
                    [void]$admx.AppendLine("        <enum id=`"$name`" valueName=`"$name`" required=`"true`">")
                    foreach ($choice in $s.Choices) {
                        $choiceId = "${name}_$choice"
                        $strings[$choiceId] = $choice
                        [void]$admx.AppendLine("          <item displayName=`"`$(string.$choiceId)`"><value><string>$(ConvertTo-XmlText $choice)</string></value></item>")
                    }
                    [void]$admx.AppendLine('        </enum>')
                    $defaultIndex = [Array]::IndexOf([string[]]$s.Choices, [string]$default)
                    [void]$presentations.AppendLine("      <presentation id=`"$name`"><dropdownList refId=`"$name`" noSort=`"true`" defaultItem=`"$([Math]::Max($defaultIndex, 0))`">$(ConvertTo-XmlText $s.Label):</dropdownList></presentation>")
                }
                default {
                    [void]$admx.AppendLine("        <text id=`"$name`" valueName=`"$name`" maxLength=`"2048`" />")
                    [void]$presentations.AppendLine("      <presentation id=`"$name`"><textBox refId=`"$name`"><label>$(ConvertTo-XmlText $s.Label):</label></textBox></presentation>")
                }
            }
            [void]$admx.AppendLine('      </elements>')
        }
    }
    [void]$admx.AppendLine('    </policy>')
}
[void]$admx.AppendLine('  </policies>')
[void]$admx.AppendLine('</policyDefinitions>')

[void]$adml.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$adml.AppendLine('<!-- Generated by build/New-PolicyTemplate.ps1 from the ErpPrinter settings schema. Do not edit by hand. -->')
[void]$adml.AppendLine("<policyDefinitionResources xmlns:xsd=`"http://www.w3.org/2001/XMLSchema`" xmlns:xsi=`"http://www.w3.org/2001/XMLSchema-instance`" revision=`"$Revision`" schemaVersion=`"1.0`" xmlns=`"http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions`">")
[void]$adml.AppendLine('  <displayName>ERP Printer</displayName>')
[void]$adml.AppendLine('  <description>Machine-wide settings for ERP Printer. Printer profiles are configured with Group Policy Preferences or Intune.</description>')
[void]$adml.AppendLine('  <resources>')
[void]$adml.AppendLine('    <stringTable>')
foreach ($id in $strings.Keys) {
    [void]$adml.AppendLine("      <string id=`"$id`">$(ConvertTo-XmlText $strings[$id])</string>")
}
[void]$adml.AppendLine('    </stringTable>')
[void]$adml.AppendLine('    <presentationTable>')
[void]$adml.Append($presentations.ToString())
[void]$adml.AppendLine('    </presentationTable>')
[void]$adml.AppendLine('  </resources>')
[void]$adml.AppendLine('</policyDefinitionResources>')

$languageDir = Join-Path $OutputDir 'en-US'
New-Item -ItemType Directory -Force -Path $languageDir | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText((Join-Path $OutputDir 'ErpPrinter.admx'), ($admx.ToString() -replace "`r?`n", "`r`n"), $utf8)
[IO.File]::WriteAllText((Join-Path $languageDir 'ErpPrinter.adml'), ($adml.ToString() -replace "`r?`n", "`r`n"), $utf8)
Write-Output "Wrote ADMX/ADML to $OutputDir"
