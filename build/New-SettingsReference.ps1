<#
.SYNOPSIS
    Generates docs/settings.md from the module's settings schema.
#>
[CmdletBinding()]
param([string] $OutputPath)
$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1 leaves $PSScriptRoot empty in param() defaults under -File, so resolve here.
if (-not $OutputPath) { $OutputPath = Join-Path $PSScriptRoot '..\docs\settings.md' }
$module = Import-Module (Join-Path $PSScriptRoot '..\src\Modules\ErpPrinter\ErpPrinter.psd1') -Force -PassThru

function Format-Default($Setting, $Resolved) {
    if ($Setting.DefaultText) { return "``$($Setting.DefaultText)``" }
    if ($Setting.Default -is [scriptblock]) {
        if ($Setting.Name -eq 'PrinterName') { return 'the profile name' }
        if ($Setting.Name -eq 'PipeName') { return '`ErpPrinter-<profile name>`' }
    }
    $value = $Resolved[$Setting.Name]
    switch ($Setting.Type) {
        'Bool' { if ($value) { return '1 (on)' } else { return '0 (off)' } }
        'Secret' { return '' }
        default { if ("$value" -eq '') { return '(empty)' } return "``$value``" }
    }
}

function Format-Type($Setting) {
    switch ($Setting.Type) {
        'Bool' { 'REG_DWORD 0/1' }
        'Int' { "REG_DWORD $($Setting.Min)-$($Setting.Max)" }
        'Choice' { 'REG_SZ: ' + (($Setting.Choices | ForEach-Object { "``$_``" }) -join ', ') }
        'Secret' { 'REG_BINARY (DPAPI), under `Secrets\<profile>`' }
        default { 'REG_SZ' }
    }
}

function Format-Cell([string] $Text) { ($Text -replace '\|', '\|' -replace "`r?`n", ' ').Trim() }

$globalDefaults = & $module { Resolve-ErpSettings -Schema $script:ErpGlobalSchema }
$profileDefaults = & $module { Resolve-ErpSettings -Schema $script:ErpProfileSchema -Context @{ Name = 'Example' } }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('<!-- Generated by build/New-SettingsReference.ps1 from the settings schema. Do not edit by hand. -->')
$lines.Add('# Settings reference')
$lines.Add('')
$lines.Add('Every setting lives in the registry. The configuration window, the MSI properties and the `Set-ErpPrinterSetting` cmdlet all write the same values.')
$lines.Add('')
$lines.Add('| Scope | Machine value (GUI, MSI, scripts) | Policy override (GPO, Intune) |')
$lines.Add('| --- | --- | --- |')
$lines.Add('| Global | `HKLM\SOFTWARE\ErpPrinter` | `HKLM\SOFTWARE\Policies\ErpPrinter` |')
$lines.Add('| Printer profile | `HKLM\SOFTWARE\ErpPrinter\Printers\<profile>` | `HKLM\SOFTWARE\Policies\ErpPrinter\Printers\<profile>` |')
$lines.Add('')
$lines.Add('A value under `Policies` wins and shows as read-only in the configuration window. A profile that exists only under `Policies` is fully managed by policy. Secrets are never read from `Policies`.')
$lines.Add('')

foreach ($scope in 'Global', 'Profile') {
    $schema = @(Get-ErpPrinterSettingSchema -Scope $scope)
    $defaults = if ($scope -eq 'Global') { $globalDefaults } else { $profileDefaults }
    $lines.Add($(if ($scope -eq 'Global') { '## Global settings' } else { '## Printer profile settings' }))
    $lines.Add('')
    foreach ($group in @($schema | ForEach-Object Group | Select-Object -Unique)) {
        $lines.Add("### $group")
        $lines.Add('')
        if ($scope -eq 'Global') {
            $lines.Add('| Name | Type | Default | Description |')
            $lines.Add('| --- | --- | --- | --- |')
        } else {
            $lines.Add('| Name | Type | Default | Backends | Description |')
            $lines.Add('| --- | --- | --- | --- | --- |')
        }
        foreach ($s in $schema | Where-Object Group -eq $group) {
            $description = $s.Label + '.'
            if ($s.Help) { $description += ' ' + $s.Help }
            $backendCell = ''
            if ($scope -eq 'Profile') {
                $backendCell = ' ' + $(if ($s.Backends.Count) { $s.Backends -join ', ' } else { 'all' }) + ' |'
            }
            $lines.Add("| ``$($s.Name)`` | $(Format-Type $s) | $(Format-Default $s $defaults) |$backendCell $(Format-Cell $description) |")
        }
        $lines.Add('')
    }
}

$utf8 = New-Object System.Text.UTF8Encoding $false
New-Item -ItemType Directory -Force -Path (Split-Path $OutputPath) | Out-Null
[IO.File]::WriteAllText($OutputPath, (($lines -join "`n") + "`n"), $utf8)
Write-Output "Wrote $OutputPath"
